function pick(setting) {
  if (setting === "ja" || setting === "en") return setting;
  return (navigator.language || "en").toLowerCase().startsWith("ja") ? "ja" : "en";
}

let setting = "auto";
try { setting = (await host.config()).lang || "auto"; } catch { /* ブラウザ確認表示・起動直後 */ }
export const LANG = pick(setting);
document.documentElement.lang = LANG;

// t("folders.items", { n: 3 }) → "3 items"
export function t(key, vars = {}) {
  const s = STRINGS[LANG][key] ?? STRINGS.ja[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

// data-i18n="key"（文字）/ data-i18n-title="key"（ツールチップ）/ data-i18n-aria="key" を一括で訳す
export function translateDom(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
}

// manifest の文言を表示言語で上書きした写しを返す。
// manifest.locales.en = { name, summary, actions: { <id>: { label, params: { <name>: { label, placeholder, options: { <value>: label } } } } } }
export function localize(mod) {
  const loc = mod?.locales?.[LANG];
  if (!loc) return mod;
  const out = { ...mod, name: loc.name ?? mod.name, summary: loc.summary ?? mod.summary };
  out.actions = (mod.actions || []).map((a) => {
    const la = loc.actions?.[a.id];
    if (!la) return a;
    return {
      ...a,
      label: la.label ?? a.label,
      params: (a.params || []).map((p) => {
        const lp = la.params?.[p.name];
        if (!lp) return p;
        return {
          ...p,
          label: lp.label ?? p.label,
          placeholder: lp.placeholder ?? p.placeholder,
          options: (p.options || []).map((o) => {
            const v = typeof o === "object" ? o.value : o;
            const l = lp.options?.[v];
            return l ? { value: v, label: l } : o;
          }),
        };
      }),
    };
  });
  return out;
}

